package game.arena;
/**
 * The SummerArena class represents a specific type of arena used during summer.
 * It implements the ArenaType interface and provides the type of the arena.
 */
public class SummerArena implements ArenaType {
    /**
     * Returns the type of the arena as a string.
     *
     * @return A string representing the type of the arena, which is "SummerArena".
     */
    public String TypeArena()
    {
        return "SummerArena";
    }

}
